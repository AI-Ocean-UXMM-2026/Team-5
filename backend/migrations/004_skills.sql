  id text PRIMARY KEY,
  label_en text NOT NULL,
  label_my text NOT NULL
);

CREATE TABLE goal_skills (
  goal_id text NOT NULL,
  skill_id text NOT NULL REFERENCES skills (id),
  position integer NOT NULL,
  PRIMARY KEY (goal_id, skill_id)
);

